<section>
    <h2>1. Komitmen</h2>
    <p>SIMPIL dan jurnal-jurnal di dalamnya menjunjung integritas ilmiah. Pedoman ini berlaku bagi penulis, reviewer, dan editor, serta menjadi dasar
       penanganan dugaan pelanggaran etika publikasi.</p>
</section>

<section>
    <h2>2. Kewajiban penulis</h2>
    <ul>
        <li><strong>Keaslian:</strong> naskah orisinal, bukan plagiarisme, tidak memuat data rekayasa atau pemalsuan, dan sumber kutipan dicantumkan.</li>
        <li><strong>Publikasi ganda:</strong> naskah belum dan tidak sedang diajukan atau diterbitkan di tempat lain.</li>
        <li><strong>Kepengarangan:</strong> semua penulis yang berkontribusi dicantumkan sebagai penulis pendamping dan telah menyetujui pengajuan.</li>
        <li><strong>Hak cipta:</strong> penulis berhak atas naskah dan menyetujui lisensi terbuka jurnal tujuan.</li>
        <li><strong>Konflik kepentingan:</strong> kepentingan finansial, pribadi, atau institusional yang dapat memengaruhi naskah wajib diungkapkan saat pengajuan.</li>
        <li><strong>Etika penelitian:</strong> penulis bertanggung jawab memastikan penelitiannya telah memenuhi ketentuan etik dari lembaga asalnya (misalnya persetujuan komisi etik bila melibatkan subjek manusia).
            SIMPIL tidak mengawasi proses penelitian itu sendiri.</li>
    </ul>
</section>

<section>
    <h2>3. Kewajiban reviewer</h2>
    <ul>
        <li>Menjaga kerahasiaan naskah dan tidak menggunakannya untuk kepentingan pribadi.</li>
        <li>Menolak penugasan jika terdapat konflik kepentingan, dan menilai secara objektif.</li>
        <li>Melaporkan dugaan plagiarisme atau pelanggaran etika kepada editor.</li>
    </ul>
</section>

<section>
    <h2>4. Kewajiban editor</h2>
    <ul>
        <li>Memutuskan berdasarkan kualitas ilmiah dan hasil review, tanpa diskriminasi.</li>
        <li>Menjaga anonimitas review dan kerahasiaan naskah selama proses berlangsung.</li>
        <li>Menindaklanjuti dugaan pelanggaran etika dan, bila terbukti, melakukan koreksi atau penarikan artikel.</li>
    </ul>
</section>

<section>
    <h2>5. Penanganan pelanggaran</h2>
    <p>Dugaan pelanggaran dilaporkan kepada editor jurnal terkait atau administrator SIMPIL. Sanksi dapat berupa penolakan naskah, koreksi atau penarikan artikel,
       dan pemberitahuan kepada institusi asal penulis.</p>
</section>
@endsection
